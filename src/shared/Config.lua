-- ⚠️ ทำไม 8 ขั้น/ด่าน ไม่ใช่ 9
--------------------------------------------------------------------------------
-- ค่าที่สั่งมาคือ "×1.1 ต่อขั้น · 9 ขั้นต่อด่าน · รวม 72 ขั้น" ซึ่งขัดกันเอง
