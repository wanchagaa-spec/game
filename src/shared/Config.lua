-- แก้อะไรอย่างอื่นอีกนิดเดียวก็หลุด
--
--     ขั้น/ด่าน | ขั้นรวม | ด่าน 4   | ด่าน 9  | ผ่านยาม
--     ----------|---------|----------|---------|--------
--      7        | 63      | 1.08 ชม. | 128 ชม. | ❌ เกินเพดาน 72 ชม.
--      **8**    | **72**  | **0.74** | **54**  | ✅ มีระยะเผื่อทั้งสองด้าน
--      9        | 81      | 0.502    | 23.0    | ⚠️ ผ่านแบบเฉียดพื้น 0.4%
